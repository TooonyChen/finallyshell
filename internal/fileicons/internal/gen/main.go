// Command gen makes the files package fileicons takes from upstream, at
// pinned versions:
//
//   - bundled/material-icon-theme.vsix: Material Icon Theme as Open VSX
//     publishes it, checked against its SHA-256;
//   - bundled/seti.vsix: VS Code's Seti theme (extensions/theme-seti),
//     packed as a VSIX with VS Code's license and Seti's notices;
//   - languages_gen.go: the file names, patterns and extensions of VS
//     Code's built-in languages, which themes map with languageIds.
//
// It needs git and the network. Run it from the package's folder:
//
//	go generate ./internal/fileicons
//
// To update, change the versions below (and the SHA-256, from the file
// Open VSX serves), run it, and check the diff and the tests.
package main

import (
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

const (
	// vscodeTag is the VS Code release the languages and Seti come from.
	vscodeTag = "1.145.2"

	materialVersion = "5.40.0"
	materialURL     = "https://open-vsx.org/api/PKief/material-icon-theme/" + materialVersion +
		"/file/PKief.material-icon-theme-" + materialVersion + ".vsix"
	materialSHA256 = "55b565f200881abfd807baf9be52fce45fd52fef013ba71b0f8394984ce1ae06"
)

func main() {
	log.SetFlags(0)
	tmp, err := os.MkdirTemp("", "fileicons-gen-")
	if err != nil {
		log.Fatal(err)
	}
	defer os.RemoveAll(tmp)

	vscode := filepath.Join(tmp, "vscode")
	run("git", "-c", "advice.detachedHead=false", "clone", "-q", "--depth", "1", "--branch", vscodeTag, "--filter=blob:none", "--sparse",
		"https://github.com/microsoft/vscode.git", vscode)
	run("git", "-C", vscode, "sparse-checkout", "set", "--no-cone",
		"/extensions/*/package.json", "/extensions/theme-seti/", "/LICENSE.txt")

	if err := writeLanguages(vscode, "languages_gen.go"); err != nil {
		log.Fatal(err)
	}
	if err := writeSeti(vscode, filepath.Join("bundled", "seti.vsix")); err != nil {
		log.Fatal(err)
	}
	if err := writeMaterial(filepath.Join("bundled", "material-icon-theme.vsix")); err != nil {
		log.Fatal(err)
	}
}

func run(name string, args ...string) {
	cmd := exec.Command(name, args...)
	cmd.Stdout, cmd.Stderr = os.Stderr, os.Stderr
	if err := cmd.Run(); err != nil {
		log.Fatalf("%s %s: %v", name, strings.Join(args, " "), err)
	}
}

// language is what a built-in extension's package.json says of a
// language.
type language struct {
	ID               string   `json:"id"`
	Extensions       []string `json:"extensions"`
	Filenames        []string `json:"filenames"`
	FilenamePatterns []string `json:"filenamePatterns"`
}

// writeLanguages writes the Go file of the languages of VS Code's
// built-in extensions, by file name, by pattern of the name alone (the
// patterns of paths, "**/...", are left out) and by extension.
func writeLanguages(vscode, out string) error {
	files, err := filepath.Glob(filepath.Join(vscode, "extensions", "*", "package.json"))
	if err != nil {
		return err
	}
	sort.Strings(files)
	names, exts, suffixes, patterns := map[string]string{}, map[string]string{}, map[string]string{}, map[string]string{}
	add := func(m map[string]string, key, id, what string) {
		key = strings.ToLower(key)
		if old, ok := m[key]; ok && old != id {
			// VS Code takes the one registered last, as here.
			log.Printf("%s %q: %s replaces %s", what, key, id, old)
		}
		m[key] = id
	}
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		var pkg struct {
			Contributes struct {
				Languages []language `json:"languages"`
			} `json:"contributes"`
		}
		if err := json.Unmarshal(data, &pkg); err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		for _, l := range pkg.Contributes.Languages {
			for _, n := range l.Filenames {
				add(names, n, l.ID, "file name")
			}
			for _, e := range l.Extensions {
				switch {
				case strings.ContainsAny(e, "*?["):
					// VS Code takes an extension with a wildcard as
					// the pattern *<extension>.
					addPattern(patterns, "*"+e, l.ID)
				case strings.HasPrefix(e, "."):
					add(exts, e, l.ID, "extension")
				default:
					// The end of a name, as VS Code matches extensions.
					add(suffixes, e, l.ID, "suffix")
				}
			}
			for _, p := range l.FilenamePatterns {
				if !strings.Contains(p, "/") {
					addPattern(patterns, p, l.ID)
				}
			}
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/gen from the built-in languages of VS Code %s; DO NOT EDIT.\n", vscodeTag)
	b.WriteString("//\n// VS Code is Copyright (c) Microsoft Corporation, under the MIT License\n// (bundled/seti.vsix holds its text).\n\n")
	b.WriteString("package fileicons\n\n")
	writeMap(&b, "languageFileNames", "the languages of file names, in lower case", names)
	writeMap(&b, "languageExtensions", "the languages of extensions, dot included, in lower case", exts)
	writeMap(&b, "languageSuffixes", "the languages of other ends of file names, in lower case", suffixes)
	writeMap(&b, "languagePatterns", "the languages of the patterns of file names (path.Match), in lower case", patterns)
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

// addPattern adds the pattern p of a file name for the language id,
// unless path.Match cannot read it.
func addPattern(m map[string]string, p, id string) {
	if _, err := path.Match(p, ""); err != nil {
		log.Printf("pattern %q of %s: %v", p, id, err)
		return
	}
	m[strings.ToLower(p)] = id
}

func writeMap(b *bytes.Buffer, name, doc string, m map[string]string) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintf(b, "// %s are %s.\nvar %s = map[string]string{\n", name, doc, name)
	for _, k := range keys {
		fmt.Fprintf(b, "\t%q: %q,\n", k, m[k])
	}
	b.WriteString("}\n\n")
}

// zipTime is the time of every file in the VSIX made here, so that the
// same sources make the same bytes.
var zipTime = time.Date(2000, 1, 1, 0, 0, 0, 0, time.UTC)

// writeSeti packs VS Code's Seti theme as a VSIX: its package.json and
// strings, the theme, its font, and the license and notices.
func writeSeti(vscode, out string) error {
	dir := filepath.Join(vscode, "extensions", "theme-seti")
	files := []struct{ from, to string }{
		{filepath.Join(dir, "package.json"), "extension/package.json"},
		{filepath.Join(dir, "package.nls.json"), "extension/package.nls.json"},
		{filepath.Join(dir, "icons", "vs-seti-icon-theme.json"), "extension/icons/vs-seti-icon-theme.json"},
		{filepath.Join(dir, "icons", "seti.woff"), "extension/icons/seti.woff"},
		{filepath.Join(dir, "ThirdPartyNotices.txt"), "extension/ThirdPartyNotices.txt"},
		{filepath.Join(vscode, "LICENSE.txt"), "extension/LICENSE.txt"},
	}
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for _, f := range files {
		data, err := os.ReadFile(f.from)
		if err != nil {
			return err
		}
		w, err := zw.CreateHeader(&zip.FileHeader{Name: f.to, Method: zip.Deflate, Modified: zipTime})
		if err != nil {
			return err
		}
		if _, err := w.Write(data); err != nil {
			return err
		}
	}
	if err := zw.Close(); err != nil {
		return err
	}
	return os.WriteFile(out, buf.Bytes(), 0o644)
}

// writeMaterial downloads Material Icon Theme's VSIX and checks it.
func writeMaterial(out string) error {
	resp, err := http.Get(materialURL)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("%s: %s", materialURL, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		return err
	}
	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != materialSHA256 {
		return fmt.Errorf("%s: SHA-256 %s, want %s", materialURL, got, materialSHA256)
	}
	return os.WriteFile(out, data, 0o644)
}
